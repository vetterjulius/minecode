import { SubGenerator, CompositionPlan } from '@minecode/core';

export const EXTENSIONS_TYPES_PATH = 'lib/extensions.ts';

const HOOK_TYPES = `export interface HookContext {
  /** The signed-in user, or null when the request is anonymous. */
  userId: string | null;
}

export type Row = Record<string, unknown>;

/** Runs before an insert. Return the row to insert (or nothing to keep it); throw to reject. */
export type BeforeCreateHook = (row: Row, context: HookContext) => Row | void | Promise<Row | void>;

/** Runs after a successful insert. Throwing here is reported to the caller as an error. */
export type AfterCreateHook = (row: Row, context: HookContext) => void | Promise<void>;
`;

function hookNames(plan: CompositionPlan): string[] {
  return plan.extensionPoints
    .filter((ep) => ep.type === 'function' && /\.(beforeCreate|afterCreate)$/.test(ep.name))
    .map((ep) => ep.name)
    .sort();
}

/** Types the extension hooks of a composition. Generated; never edit. */
export function buildExtensionTypes(plan: CompositionPlan): string {
  const entries = hookNames(plan).map(
    (name) =>
      `    '${name}'?: ${name.endsWith('.beforeCreate') ? 'BeforeCreateHook' : 'AfterCreateHook'};`
  );
  return `// Generated by Minecode. Do not edit; write your code in extensions/index.ts.
${HOOK_TYPES}
export interface Extensions {
  hooks?: {
${entries.join('\n')}
  };
}
`;
}

/** One-time scaffold of the file where application code plugs into the generated app. */
export function buildExtensionsScaffold(plan: CompositionPlan): string {
  const examples = hookNames(plan)
    .slice(0, 2)
    .map((name) =>
      name.endsWith('.beforeCreate')
        ? `    // '${name}': async (row, { userId }) => ({ ...row }),`
        : `    // '${name}': async (row, { userId }) => {},`
    );
  return `import type { Extensions } from '../generated/lib/extensions';

/**
 * Your code. Minecode creates this file once and never overwrites it.
 * Generated routes call the hooks registered here; see generated/lib/extensions.ts for the types
 * and config/extensions.ts for all extension points of this application.
 */
export const extensions: Extensions = {
  hooks: {
${examples.join('\n')}
  },
};
`;
}

export class CommonExtensionsSubGenerator implements SubGenerator {
  public readonly id = 'common-extensions';

  public generate(plan: CompositionPlan): Record<string, string> {
    const files: Record<string, string> = {};

    if (plan.extensionPoints.length > 0) {
      let extContent = `// Extension points and contributions for ${plan.applicationName}\n\n`;
      extContent += `export const extensionPoints = {\n`;
      for (const ep of plan.extensionPoints) {
        extContent += `  "${ep.name}": {\n`;
        extContent += `    id: "${ep.id}",\n`;
        extContent += `    type: "${ep.type}",\n`;
        extContent += `    description: ${JSON.stringify(ep.description || '')},\n`;
        extContent += `    schema: ${JSON.stringify(ep.schema || {})},\n`;
        extContent += `    contributions: ${JSON.stringify(ep.contributions, null, 4)},\n`;
        extContent += `  },\n`;
      }
      extContent += `} as const;\n`;
      files['config/extensions.ts'] = extContent;
    }

    if (hookNames(plan).length > 0) {
      files[EXTENSIONS_TYPES_PATH] = buildExtensionTypes(plan);
      files['extensions/index.ts'] = buildExtensionsScaffold(plan);
    }

    if (plan.permissions.length > 0) {
      let permContent = `// Permissions list for ${plan.applicationName}\n\n`;
      permContent += `export const permissions = {\n`;
      for (const perm of plan.permissions) {
        permContent += `  /** ${perm.description || 'Permission for ' + perm.name} */\n`;
        permContent += `  "${perm.name}": "${perm.id}",\n`;
      }
      permContent += `} as const;\n\n`;
      permContent += `export type Permission = keyof typeof permissions;\n`;
      files['config/permissions.ts'] = permContent;
    }

    return files;
  }
}
